# 1. edgeR NB fit with a group-means design; one fitted mu per group per gene
# ---------------------------------------------------------------------------

# Match the ZINB training scale EXACTLY (see dynamic_tar_script.R): TMMwsp to the
# same reference sample, then offset = log(1 / multiplier). The reference sample
# gets multiplier ~ 1 => offset ~ 0, i.e. the brms `offset = 0` reference scale.
se_test <- se_monocytic |>
  tidybulk::scale_abundance(method = "TMMwsp", reference_sample = ref_sample_name)

counts <- assay(se_test, "counts")
meta   <- as.data.frame(colData(se_test))
offset_vec <- log(1 / meta$multiplier)            # same definition as training

# Category for the SAVI cohorts; the atlas reference column has Category = NA.
group <- as.character(meta$Category)
group[is.na(group)] <- "reference"
meta$group <- factor(group) |> fct_relevel("reference")

dge <- DGEList(counts = counts, samples = meta, genes = as.data.frame(rowData(se_test)))
reference <- which(colnames(dge$counts) == ref_sample_name)

# Use the scale_abundance offset directly (overrides edgeR's lib.size * norm).
dge$offset <- matrix(offset_vec, nrow = nrow(dge), ncol = ncol(dge), byrow = TRUE)

design <- model.matrix(~ 0 + group, data = meta)
colnames(design) <- sub("^group", "", colnames(design))

dge <- estimateDisp(dge, design)
fit <- glmQLFit(dge, design)

# NB dispersion edgeR used for the GLM weights (trended, falling back as needed).
nb_dispersion <- if (!is.null(dge$trended.dispersion)) {
  dge$trended.dispersion
} else if (!is.null(dge$tagwise.dispersion)) {
  dge$tagwise.dispersion
} else {
  rep_len(dge$common.dispersion, nrow(dge))
}

# Fitted NB mean (log scale) for a cohort, evaluated at offset = 0 (the brms
# reference scale, since offset_vec[reference] = log(1/multiplier_ref) = 0).
#
# IMPORTANT: we do NOT read fit$coefficients here. edgeR's DGEList pipeline
# (glmFit/glmQLFit) internally rescales a supplied offset by a constant, so its
# coefficients are shifted on the ABSOLUTE scale (the shift cancels in group-vs-
# group contrasts, but NOT when comparing absolute mu to an external baseline as
# we do here). We therefore take the point estimate from the raw NB MLE
# (mglmOneGroup with the offset applied directly), which gives log(mu) at
# offset 0 exactly, and keep glmQLFit only for the QL-shrunk Wald SE (which a
# constant offset shift does not affect).
edger_log_mu <- function(gene_id, cohort, fit, nb_dispersion, counts, offset_vec) {
  gi <- match(gene_id, rownames(fit))
  if (is.na(gi)) stop("Gene ", gene_id, " not in edgeR fit.")
  if (!cohort %in% colnames(fit$coefficients)) stop("Group ", cohort, " not in design.")

  disp <- nb_dispersion[gi]
  j    <- which(fit$samples$group == cohort)
  # Genuine NB MLE of log(mu) at offset 0 (offset_vec[reference] = 0).
  log_mu <- edgeR::mglmOneGroup(matrix(counts[gi, j], nrow = 1),
                                dispersion = disp, offset = offset_vec[j])

  # QL Wald SE: SE = sqrt(s2.post * (X' W X)^{-1}_kk). Invariant to a constant
  # offset shift, so it is safe to pair with the MLE above.
  mu_all <- fit$fitted.values[gi, ]
  W      <- mu_all / (1 + disp * mu_all)            # NB IRLS working weights
  cov_un <- solve(t(fit$design) %*% (W * fit$design))
  se     <- sqrt(fit$s2.post[gi] * cov_un[cohort, cohort])

  list(
    log_mu = unname(log_mu),                        # mu at reference depth (log)
    se     = unname(se),
    df     = unname(fit$df.residual.adj[gi])
  )
}

