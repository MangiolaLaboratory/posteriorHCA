# ============================================================================
# mu_test.R
# Test a user cohort (e.g. SAVI, 5 donors) for one gene against the healthy
# atlas baseline, by comparing the two FITTED NB MEAN PARAMETERS (mu):
#
#   * baseline mu : brms zero-inflated NB fit. The NB mean parameter is
#                   mu = exp(linear predictor) = posterior_linpred(transform=FALSE)
#                   exponentiated  (NOT posterior_epred, which for ZINB returns
#                   (1 - zi) * mu, the expected count). Marginalised over the
#                   universal healthy covariate grid -> draws of log(mu).
#   * cohort mu   : edgeR NB fit with a group-means design (~0 + group), with the
#                   offset set to the SAME scale_abundance offset = log(1/multiplier)
#                   the ZINB was trained with (reference sample -> offset 0, so
#                   log(mu) at offset 0 is on the baseline's scale). KEY FINDING:
#                   do NOT read fit$coefficients - edgeR's DGEList pipeline
#                   internally rescales a supplied offset by a constant, so its
#                   coefficients are shifted on the ABSOLUTE scale (the shift
#                   cancels in group-vs-group contrasts but NOT when comparing an
#                   absolute mu to an external baseline, which is what we do). We
#                   take the point estimate from the raw NB MLE (mglmOneGroup with
#                   the offset applied directly) and use glmQLFit only for the
#                   QL-shrunk Wald SE (invariant to a constant offset shift).
#
# Offset equivalence (verified): calcNormFactors(TMMwsp) and scale_abundance(TMMwsp)
# give offsets that are identical up to a global constant (correlation 1), so the
# normalisation is the same; scale_abundance is used only because it re-anchors the
# reference sample to offset 0, matching the brms training convention exactly.
#
# Tests (two nulls; the second is the biomarker-appropriate one):
#   PREDICTION-INTERVAL (conservative): cohort vs the FULL marginal log(mu) spread
#     (welch_t_from_mean_se with se = sd_log_mu, + empirical upper-tail rank).
#     Asks "is the cohort outside the entire cloud of healthy conditions?".
#   DEVIATION-FROM-MEAN (lever a): cohort vs the posterior of the healthy GRAND
#     MEAN (grid collapsed per draw; se = sd_grand_mean << sd_log_mu, + rank).
#     Asks "is the cohort mean shifted from the average healthy mu?".
#   bootstrapping_p_value() - non-parametric KS of observed counts vs the posterior
#     PREDICTIVE draws; kept as a reference but note (see report) that testing on
#     the predicted-count scale conflates NB + zero-inflation sampling noise and is
#     under-powered relative to the mu (linpred) tests above.
#
# Self-contained: loads cached objects built by
#   * mu_test_build_env.R       -> se_monocytic + ref_sample_name
#   * mu_test_epred_baseline.R  -> per-gene log(mu) draws (posterior_linpred) +
#                                  per-draw grand-mean draws
# and the per-gene posterior-predictive draws from the qmd store on disk.
# ============================================================================

