# Parametric: Welch t-test from two (mean, SE, n) summaries.
welch_t_from_mean_se <- function(mean1, se1, n1, mean2, se2, n2) {
  sd1 <- se1 * sqrt(n1)
  sd2 <- se2 * sqrt(n2)
  se_diff <- sqrt(se1^2 + se2^2)
  t_stat  <- (mean1 - mean2) / se_diff
  df <- (sd1^2 / n1 + sd2^2 / n2)^2 /
    ((sd1^2 / n1)^2 / (n1 - 1) + (sd2^2 / n2)^2 / (n2 - 1))
  p_value <- 2 * pt(abs(t_stat), df = df, lower.tail = FALSE)
  data.frame(
    mean1 = mean1, mean2 = mean2, mean_diff = mean1 - mean2,
    se_diff = se_diff, t = t_stat, df = df, p_value = p_value
  )
}

# Non-parametric: bootstrap the chosen metric (default KS) of observed values
# vs the baseline draws, against a null built by resampling the draws.
# focal_draws are the baseline values at the quantile positions matching the
# observed sample (deterministic, representative reference); the bootstrap null
# resamples the full baseline to calibrate the statistic.
bootstrapping_p_value <-
  function(obs, draws, n_bootstrap = 1000, seed = NULL,
           metric = "ks.test", alternative = "greater", detail = FALSE) {
    if (!is.null(seed)) set.seed(seed)
    draws <- sort(draws)
    draws.p <- (1:length(draws) - 0.5) / length(draws)
    obs.p <- (1:length(obs) - 0.5) / length(obs)
    focal_draws <- draws[sapply(obs.p, function(x) which.min(abs(x - draws.p)))]
    bootstrap_draws <- lapply(1:n_bootstrap, function(i) {
      sample(draws, length(obs), replace = TRUE)
    })
    focal_metric <- do.call(metric, list(obs, focal_draws))$statistic
    bootstrap_metric <- sapply(bootstrap_draws, function(x) {
      do.call(metric, list(focal_draws, x))$statistic
    })
    p_val_raw <- (
      sum(focal_metric < bootstrap_metric) +
        sum(focal_metric == bootstrap_metric) / 2
    ) / length(bootstrap_metric)
    p_vals <- c(greater = p_val_raw,
                less = 1 - p_val_raw,
                two.sided = 2 * min(p_val_raw, 1 - p_val_raw))
    if (detail) {
      return(list(p.value = p_vals,
                  focal_metric = focal_metric,
                  bootstrap_metric = bootstrap_metric,
                  focal_draws = focal_draws,
                  bootstrap_draws = bootstrap_draws))
    }
    unname(p_vals[alternative])
  }

# Per-gene, per-cohort driver.
test_gene_cohort <- function(gene_id, cohort, fit, se,
                             baseline = NULL, mu_baseline = NULL,
                             nb_dispersion, counts, offset_vec,
                             metric = "ks.test", alternative = "greater",
                             n_bootstrap = 1000, seed = 1) {
  if (is.null(baseline))    baseline    <- get_baseline_for_gene(gene_id)
  if (is.null(mu_baseline)) mu_baseline <- get_mu_baseline_for_gene(gene_id)

  # edgeR cohort mu (one fitted NB mean + SE), on the log scale at ref depth.
  cm <- edger_log_mu(gene_id, cohort, fit, nb_dispersion, counts, offset_vec)

  # Parametric test on log(mu): cohort estimate vs the baseline mu distribution.
  # se1 = baseline SD = healthy mu heterogeneity (universal baseline); the
  # baseline mean is treated as well-determined (n1 = n_draws).
  welch <- welch_t_from_mean_se(
    mean1 = mu_baseline$mean_log_mu, se1 = mu_baseline$sd_log_mu,
    n1    = mu_baseline$n_draws,
    mean2 = cm$log_mu, se2 = cm$se, n2 = cm$df + 1
  )

  # Robust complement: where does the cohort log(mu) fall in the baseline draws?
  emp_p_upper <- mean(mu_baseline$log_mu >= cm$log_mu)

  # Lever (a) — deviation from the healthy MEAN (credible, not prediction).
  # Parametric: se1 = SD of the grand-mean draws = SE of the healthy mean.
  welch_mean <- welch_t_from_mean_se(
    mean1 = mu_baseline$mean_grand_mean, se1 = mu_baseline$sd_grand_mean,
    n1    = mu_baseline$n_grand,
    mean2 = cm$log_mu, se2 = cm$se, n2 = cm$df + 1
  )
  # Non-parametric: rank the cohort log(mu) within the grand-mean posterior.
  emp_p_mean_upper <- mean(mu_baseline$grand_mean_draws >= cm$log_mu)
  emp_p_mean_two   <- 2 * min(emp_p_mean_upper, 1 - emp_p_mean_upper)

  # Non-parametric bootstrap (rank-based KS) on the natural count scale.
  samples <- rownames(fit$samples)[which(fit$samples$group == cohort)]
  obs <- assay(se[gene_id, samples], "counts")[1, ]
  boot_p <- bootstrapping_p_value(
    obs, baseline$y_rep, n_bootstrap = n_bootstrap, seed = seed,
    metric = metric, alternative = alternative
  )

  list(
    gene_id       = gene_id,
    cohort        = cohort,
    cohort_log_mu = cm$log_mu,
    cohort_mu     = exp(cm$log_mu),
    cohort_se     = cm$se,
    welch         = cbind(cohort = cohort, welch),
    emp_p_upper   = emp_p_upper,
    welch_mean       = cbind(cohort = cohort, welch_mean),
    emp_p_mean_upper = emp_p_mean_upper,
    emp_p_mean_two   = emp_p_mean_two,
    bootstrap_p   = boot_p
  )
}

