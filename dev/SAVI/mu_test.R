# Posterior PREDICTIVE draws (counts) per gene -> used by the non-parametric test.
gene_baseline_draws_store <- readRDS(baseline_draws_rds)

get_baseline_for_gene <- function(gene_id) {
  row <- gene_baseline_draws_store[gene_baseline_draws_store$.feature == gene_id, ]
  if (!nrow(row)) stop("No predictive baseline draws stored for gene ", gene_id)
  y_rep <- row$counts_scaled[[1L]]
  list(y_rep = y_rep, n_draws = length(y_rep))
}

# NB MEAN PARAMETER mu draws (log scale) per gene -> used by the parametric test.
# Generated by mu_test_epred_baseline.R via posterior_linpred(transform = FALSE).
get_mu_baseline_for_gene <- function(gene_id) {
  if (!file.exists(epred_baseline_rds)) {
    stop("Missing mu baseline cache. Run mu_test_epred_baseline.R first.")
  }
  ep <- readRDS(epred_baseline_rds)
  if (!identical(ep$gene_id, gene_id)) {
    stop("Cached mu baseline is for ", ep$gene_id, ", not ", gene_id,
         ". Re-run mu_test_epred_baseline.R for this gene.")
  }
  list(
    log_mu      = ep$log_mu,
    mean_log_mu = ep$mean_log_mu,
    sd_log_mu   = ep$sd_log_mu,   # universal/marginal SD = healthy mu heterogeneity
    median_mu   = ep$median_mu,
    n_draws     = ep$n_draws,
    # Lever (a): posterior of the healthy GRAND MEAN (grid collapsed per draw).
    # sd_grand_mean << sd_log_mu: uncertainty in the mean, not the spread.
    grand_mean_draws = ep$grand_mean_draws,
    mean_grand_mean  = ep$mean_grand_mean,
    sd_grand_mean    = ep$sd_grand_mean,
    n_grand          = ep$n_grand
  )
}

